#!/usr/bin/env python3
"""Generates build/abi-probe.c from the OASIS PKCS#11 v3.2 headers in the vendor/pkcs11 submodule.

The probe is the test suite's independent layout oracle: compiled by each CI leg's own C
toolchain against the official headers, it prints sizeof/offsetof for every struct the header
defines. The managed AbiOracleTests compare the library's struct definitions against that output,
so a wrong field order, width or packing fails on the platform where it is wrong.

Field names come from parsing pkcs11t.h. The three CK_FUNCTION_LIST tables are not parsed: the
probe expands pkcs11f.h through the same CK_PKCS11_FUNCTION_INFO X-macro pkcs11.h uses to build
them, so their slots come from the compiler, not from this script.

Re-run after bumping the submodule:  python3 build/generate-abi-probe.py
"""

import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent
HEADERS = ROOT.parent / "vendor" / "pkcs11" / "published" / "3-02"
OUT = ROOT / "abi-probe.c"

DECLARATOR = re.compile(r"[A-Za-z_]\w*\s+\**\s*(?P<name>[A-Za-z_]\w*)(\s*\[\s*\w+\s*\])?")


def parse_structs(text: str) -> list[tuple[str, list[str]]]:
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    structs = []
    for tag, body, name in re.findall(r"typedef\s+struct\s+(\w+)\s*\{(.*?)\}\s*(\w+)\s*;", text, flags=re.S):
        if tag != name:
            raise SystemExit(f"struct tag {tag} differs from typedef name {name}")
        fields = []
        for decl in (d.strip() for d in body.split(";")):
            if not decl:
                continue
            m = DECLARATOR.fullmatch(decl)
            if m is None:
                raise SystemExit(f"{name}: unrecognised member declaration '{decl}'")
            fields.append(m.group("name"))
        structs.append((name, fields))
    return structs


def parse_scalar_params(text: str) -> list[str]:
    """Mechanism parameter types that C declares as a bare CK_ULONG (CK_RC2_PARAMS, ...)."""
    return re.findall(r"^typedef\s+CK_ULONG\s+(CK_\w+_PARAMS)\s*;", text, flags=re.M)


def main() -> None:
    header = (HEADERS / "pkcs11t.h").read_text()
    structs = parse_structs(header)
    scalars = parse_scalar_params(header)
    lines = [
        "/* GENERATED by build/generate-abi-probe.py from vendor/pkcs11/published/3-02/pkcs11t.h. Do not edit. */",
        "/*",
        " * PKCS#11 ABI oracle. Prints one line per struct and per member, as laid out by THIS",
        " * compiler for THIS target with the packing the OASIS headers prescribe:",
        " *   S <struct> <sizeof>",
        " *   F <struct> <index> <member> <offsetof> <sizeof member>",
        " * A parameter type C declares as a bare CK_ULONG is reported as one member named (scalar).",
        " */",
        "#include <stddef.h>",
        "#include <stdio.h>",
        "",
        "/* The five platform macros pkcs11.h requires, as its own header comment describes them.",
        "   Nothing is called, so no import/export decoration is needed. */",
        "#define CK_PTR *",
        "#define CK_DECLARE_FUNCTION(returnType, name) returnType name",
        "#define CK_DECLARE_FUNCTION_POINTER(returnType, name) returnType (* name)",
        "#define CK_CALLBACK_FUNCTION(returnType, name) returnType (* name)",
        "#ifndef NULL_PTR",
        "#define NULL_PTR 0",
        "#endif",
        "",
        "/* Windows Cryptoki structures are 1-byte packed; the includer sets it (pkcs11.h). */",
        "#ifdef _WIN32",
        "#pragma pack(push, cryptoki, 1)",
        "#endif",
        '#include "pkcs11.h"',
        "#ifdef _WIN32",
        "#pragma pack(pop, cryptoki)",
        "#endif",
        "",
        "static unsigned idx;",
        '#define S(T) (printf("S %s %u\\n", #T, (unsigned)sizeof(T)), idx = 0)',
        "#define F(T, m) F_(T, m)",
        '#define F_(T, m) printf("F %s %u %s %u %u\\n", #T, idx++, #m, (unsigned)offsetof(T, m), (unsigned)sizeof(((T *)0)->m))',
        '#define SCALAR(T) printf("F %s 0 (scalar) 0 %u\\n", #T, (unsigned)sizeof(T))',
        "",
        "int main(void)",
        "{",
    ]
    for name, fields in structs:
        lines.append(f"    S({name});")
        lines.extend(f"    F({name}, {field});" for field in fields)
    for name in scalars:
        lines += [f"    S({name});", f"    SCALAR({name});"]

    # The function lists, slot by slot, through the header's own X-macro.
    lines += [
        "",
        "    /* Function lists: pkcs11f.h expanded exactly as pkcs11.h does to define them. */",
        "#define CK_PKCS11_FUNCTION_INFO(name) F(LIST, name);",
    ]
    for table, guard in (("CK_FUNCTION_LIST_3_2", None),
                         ("CK_FUNCTION_LIST_3_0", "CK_PKCS11_3_0_ONLY"),
                         ("CK_FUNCTION_LIST", "CK_PKCS11_2_0_ONLY")):
        lines += [f"#define LIST {table}", f"    S({table});", f"    F({table}, version);"]
        if guard:
            lines.append(f"#define {guard} 1")
        lines.append('#include "pkcs11f.h"')
        if guard:
            lines.append(f"#undef {guard}")
        lines.append("#undef LIST")
    lines += ["#undef CK_PKCS11_FUNCTION_INFO", "    return 0;", "}", ""]

    OUT.write_text("\n".join(lines), newline="\n")
    print(f"wrote {OUT.relative_to(ROOT.parent)}: {len(structs)} structs, {len(scalars)} scalar parameter types, 3 function lists")


if __name__ == "__main__":
    main()
